#!/usr/bin/env python3
"""Compile GLSL shaders to SPIR-V C arrays: gen_spirv_inc.py out.inc name=file.frag|.vert|.comp ... (needs glslc;
the stage comes from the extension)."""
import struct, subprocess, sys, tempfile, os

out = sys.argv[1]
lines = ["// Generated by tools/gen_spirv_inc.py from tools/shaders (glslc -O --target-env=vulkan1.0). Do not edit.\n"]
for spec in sys.argv[2:]:
    name, path = spec.split("=")
    with tempfile.TemporaryDirectory() as d:
        spv = os.path.join(d, "x.spv")
        subprocess.check_call(["glslc", "-O", "--target-env=vulkan1.0", path, "-o", spv])
        data = open(spv, "rb").read()
    words = struct.unpack("<%dI" % (len(data) // 4), data)
    lines.append("// %s\nconst uint32_t %s[] = {\n" % (path, name))
    for i in range(0, len(words), 9):
        lines.append("    " + ", ".join("0x%08x" % w for w in words[i:i + 9]) + ",\n")
    lines.append("};\n")
open(out, "w").write("".join(lines))
