#!/usr/bin/env python3
"""Embed Hades' Lua mods (games/hades/mods/<mod>/) in games/hades/mods_data.h (committed, so a build needs nothing
else). Each file is served to the game as Content/Mods/<Mod>/<path> (see games/hades/game.cpp). Run after changing a
mod file.

Usage: python tools/gen_mods.py
"""
import os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODS = {'hephaistos': 'Hephaistos'}  # folder -> name under Content/Mods


def cstr(data: bytes) -> str:
    # Raw string literals have a length limit on some compilers: emit chunks.
    out = []
    for i in range(0, len(data), 8000):
        chunk = data[i:i + 8000].decode('utf-8')
        out.append('R"_mod_(' + chunk + ')_mod_"')
    return '\n        '.join(out) if out else '""'


def main():
    lines = ['// Generated by tools/gen_mods.py from games/hades/mods. Do not edit.', '#pragma once', '',
             'struct ModFile {', '    const char* path;  // under Content/', '    const char* data;', '};', '',
             'inline const ModFile kModFiles[] = {']
    for folder, name in MODS.items():
        base = os.path.join(root, 'games', 'hades', 'mods', folder)
        for dirpath, _, files in sorted(os.walk(base)):
            for f in sorted(files):
                if not f.endswith('.lua'):
                    continue
                full = os.path.join(dirpath, f)
                rel = os.path.relpath(full, base).replace(os.sep, '/')
                data = open(full, 'rb').read()
                lines.append(f'    {{"Mods/{name}/{rel}",\n        {cstr(data)}}},')
    lines.append('};')
    open(os.path.join(root, 'games', 'hades', 'mods_data.h'), 'w').write('\n'.join(lines) + '\n')
    print(f'{sum(1 for l in lines if l.startswith("    {"))} files')


if __name__ == '__main__':
    main()
