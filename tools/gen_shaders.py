#!/usr/bin/env python3
"""Compile runtime/shaders/*.vert|*.frag to SPIR-V and embed them in runtime/src/shaders_spv.h (committed, so a
build needs no shader compiler). Run after editing a shader.

Usage: python tools/gen_shaders.py [glslc]   (default: the Android NDK's, or glslc on PATH)
"""
import glob
import os
import shutil
import struct
import subprocess
import sys
import tempfile

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def find_glslc():
    if len(sys.argv) > 1:
        return sys.argv[1]
    sdk = os.environ.get('ANDROID_HOME', os.path.expanduser('~/Library/Android/sdk'))
    for p in sorted(glob.glob(os.path.join(sdk, 'ndk', '*', 'shader-tools', '*', 'glslc*'))):
        return p
    return shutil.which('glslc') or sys.exit('glslc not found (Android NDK shader-tools or Vulkan SDK)')


def main():
    glslc = find_glslc()
    out = ['// Generated by tools/gen_shaders.py from runtime/shaders. Do not edit.', '#pragma once', '#include <cstdint>', '']
    for src in sorted(glob.glob(os.path.join(root, 'runtime', 'shaders', '*.*'))):
        name = os.path.basename(src).replace('.', '_')
        with tempfile.TemporaryDirectory() as d:
            spv = os.path.join(d, 'out.spv')
            subprocess.run([glslc, '-O', '--target-env=vulkan1.0', src, '-o', spv], check=True)
            data = open(spv, 'rb').read()
        words = struct.unpack(f'<{len(data) // 4}I', data)
        out.append(f'inline constexpr uint32_t k_{name}[] = {{')
        for i in range(0, len(words), 8):
            out.append('    ' + ', '.join(f'0x{w:08x}' for w in words[i:i + 8]) + ',')
        out.append('};')
        out.append('')
        print(f'{os.path.basename(src)}: {len(data)} bytes')
    open(os.path.join(root, 'runtime', 'src', 'shaders_spv.h'), 'w').write('\n'.join(out))


if __name__ == '__main__':
    main()
